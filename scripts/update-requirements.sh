#!/bin/sh
# Regenerates requirements.txt: every dependency of pygeoapi, pinned to the
# version resolved now. Run it after changing PYGEOAPI_VERSION or the base image
# tag, and commit the result. requirements-extra.txt is not involved: it is
# edited by hand and installed afterwards, constrained to these versions.
#
# Resolves inside the same -devel image as the wheels stage, with the versions
# read from the Dockerfile ARG defaults, and with the packages that image ships
# (GDAL, numpy, pyarrow, pip...) as constraints, as the build does. Those
# packages are left out of requirements.txt: they belong to the base image.
# pygeoapi is left out too, since PYGEOAPI_VERSION pins it.
#
# CONTAINER_ENGINE selects podman or docker (default: podman if installed).
set -eu

cd "$(dirname "$0")/.."

arg() {
    sed -n "s/^ARG $1=//p" Dockerfile
}

GDAL_VERSION=$(arg GDAL_VERSION)
PYTHON_VERSION=$(arg PYTHON_VERSION)
PYGEOAPI_VERSION=$(arg PYGEOAPI_VERSION)
IMAGE=docker.io/ndscprm/gdal:${GDAL_VERSION}-py${PYTHON_VERSION}-devel

if [ -z "${CONTAINER_ENGINE:-}" ]; then
    if command -v podman >/dev/null 2>&1; then
        CONTAINER_ENGINE=podman
    else
        CONTAINER_ENGINE=docker
    fi
fi

echo "resolving with $IMAGE and pygeoapi $PYGEOAPI_VERSION" >&2

"$CONTAINER_ENGINE" run --rm --entrypoint sh \
    -e PYGEOAPI_VERSION="$PYGEOAPI_VERSION" "$IMAGE" -c '
        set -e
        pip freeze --all > /tmp/base-constraints.txt
        pip install --quiet --no-cache-dir --use-pep517 \
            -c /tmp/base-constraints.txt "pygeoapi==$PYGEOAPI_VERSION" >&2
        pip freeze --all | grep -vxFf /tmp/base-constraints.txt | grep -iv "^pygeoapi=="
    ' > requirements.txt.new

{
    echo "# generated by scripts/update-requirements.sh, do not edit"
    echo "# dependencies of pygeoapi $PYGEOAPI_VERSION on $IMAGE"
    cat requirements.txt.new
} > requirements.txt
rm -f requirements.txt.new

echo "requirements.txt: $(grep -cv '^#' requirements.txt) packages" >&2
